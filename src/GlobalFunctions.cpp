// Subroutine: readConfigFile
//-----------------------------------------------------------------------------------------------------------------------------
std::vector<std::string> readConfigFile(const std::string& filename) {
    std::vector<std::string> results;
    std::ifstream infile(filename);

    if (!infile) {
        std::cerr << "Error: cannot open " << filename << "\n";
        std::exit(EXIT_FAILURE);
        return results;  // empty
    }

    std::string line;
    while (std::getline(infile, line)) {
        std::string trimmed = trim_left(line);

        // Skip empty or commented lines
        if (trimmed.empty() || trimmed[0] == '#')
            continue;

        results.push_back(trimmed);
    }

    if (results.size() < 2 || results.size() > 2){
        std::cerr << "Error: Cannot fetch the address of 2 input files (check __INPUT_FILE_NAMES__.txt content)." << "\n";
        std::exit(EXIT_FAILURE);
    }

    return results;
}
