// Subroutine: WRITE_BIGENDIAN
//-----------------------------------------------------------------------------------------------------------------------------
template <typename T>
void write_bigendian(std::ofstream& file, T* buffer, INT32 count) {
	char* _buf = new char[sizeof(T)];
	for (INT32 i = 0; i < count; i++) {
		swap_endian((char*)(buffer + i), _buf, sizeof(T));
		file.write(_buf, sizeof(T));
	}
	delete[] _buf;
}

