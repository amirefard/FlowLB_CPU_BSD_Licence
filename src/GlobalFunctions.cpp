// Subroutine: trim_left
//-----------------------------------------------------------------------------------------------------------------------------
// Helper to trim leading whitespace
static inline std::string trim_left(const std::string& s) {
    INT32 pos = s.find_first_not_of(" \t\r\n");
    return (pos == std::string::npos) ? "" : s.substr(pos);
}
