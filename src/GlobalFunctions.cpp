// Subroutine: SWAP_ENDIAN
//-----------------------------------------------------------------------------------------------------------------------------
void swap_endian(char* buffer, INT32 size) {
	for (INT32 b = 0; b < size / 2; b++) {
		char temp = buffer[b];
		buffer[b] = buffer[size - 1 - b];
		buffer[size - 1 - b] = temp;
	}
}
//=============================================================================================================================
//=============================================================================================================================
//-----------------------------------------------------------------------------------------------------------------------------
// Subroutine: SWAP_ENDIAN
//-----------------------------------------------------------------------------------------------------------------------------
void swap_endian(char* buffer3, char* buffer2, INT32 size) {
	for (INT32 b = 0; b < size; b++) {
		buffer2[b] = buffer3[size - 1 - b];
	}

}
